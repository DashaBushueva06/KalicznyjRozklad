# Вміст: Глобальні константи, мережеві параметри сервера, налаштування режиму тестування (дебагу) та автоматичне формування шляхів до бази даних і файлу Excel.
#
# Зв'язки: Використовує стандартні системні бібліотеки Python (os, pathlib) для безпечної роботи з операційною системою комп'ютера.
#
# Експортується до:
#   1. database/connection.py — для передачі рядка підключення до бази даних (DATABASE_URL).
#   2. storage/excel_handler.py — для передачі точного шляху до файлу Excel (EXCEL_PATH).
#   3. server/app.py — для передачі прапорця режиму розробника (DEBUG_MODE).
#   4. main.py — для передачі мережевої адреси та порту (SERVER_HOST, SERVER_PORT).

import os
from pathlib import Path

# Динамічно обчислюємо шлях до кореня проекту, піднімаючись на два рівні вгору від цього файлу
BASE_DIR = Path(__file__).resolve().parent.parent

# Формуємо шляхи до папки з даними та конкретних файлів сховища
DATA_DIR = BASE_DIR / "data"
DB_PATH = DATA_DIR / "university.db"
EXCEL_PATH = DATA_DIR / "init_data.xlsx"

# Створюємо спеціальний рядок підключення (URL), який вказує SQLAlchemy на базу SQLite
DATABASE_URL = f"sqlite:///{DB_PATH}"

# Запитуємо у системи мережеву адресу сервера; якщо її немає — використовуємо локальний хост (127.0.0.1)
SERVER_HOST = os.environ.get("SERVER_HOST", "127.0.0.1")
# Запитуємо у системи номер порту і примусово перетворюємо його на ціле число; за замовчуванням — 5000
SERVER_PORT = int(os.environ.get("SERVER_PORT", 5000))

# Вмикаємо режим розробника (автоперезавантаження та дебагер помилок у браузері)
DEBUG_MODE = True