# Вміст: Ініціалізація екземпляра веб-сервера (Flask app), налаштування його параметрів та підключення маршрутизаторівсторінок.
#
# Зв'язки: Імпортує server/routes.py для реєстрації веб-сторінок всередині додатка.
# Імпортує config/settings.py для отримання режиму тестування.
#
# Експортується до: main.py (який безпосередньо вмикає сервер і відкриває до нього доступ через мережу).

# Імпортуємо головний клас Flask, який буде обробляти HTTP-запити та керувати сервером
from flask import Flask
# Імпортуємо прапорець (True/False), який визначає, чи запускати сервер у режимі розробника (дебагу)
from config.settings import DEBUG_MODE


def create_app() -> Flask:
    """
    Ініціалізація та конфігурація Flask-додатка.
    Маршрути імпортуються всередині контексту додатка.
    """
    # Створюємо об'єкт сервера і вказуємо Flask шукати HTML-шаблони в директорії server/templates
    app = Flask(__name__, template_folder='templates')

    # Задаємо секретний ключ, який необхідний для безпечного шифрування сесій та Flash-повідомлень
    app.config['SECRET_KEY'] = 'university_management_secure_key_123'
    # Записуємо режим роботи сервера (True для розробки, False для захищеного робочого режиму)
    app.config['DEBUG'] = DEBUG_MODE

    # Штучно створюємо контекст (робоче середовище) додатка для безпечного налаштування компонентів
    with app.app_context():
        # Динамічно імпортуємо маршрути сторінок, що повністю запобігає помилці циклічного імпорту
        import server.routes

    # Повертаємо повністю сконфігурований об'єкт сервера з функції
    return app

# Викликаємо функцію і створюємо глобальний екземпляр сервера для запуску через main.py
app = create_app()